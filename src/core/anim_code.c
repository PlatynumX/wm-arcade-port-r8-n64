/* ================================================================== *
 * The announcer speech group.
 *
 * `CALL_MISSES` and its eleven siblings are all the same three lines --
 * CREATE a SOUND_PID process, SLEEP, ADD_IF_SILENT with a table and a
 * percentage -- so what a call site needs is a delay and two numbers, and
 * wm_announce_calls[] carries all three straight out of DCSSOUND.ASM.
 *
 * The process is modelled as a pending slot counted down by
 * wm_anim_code_tick, which is where the source's other timed sound state
 * (razor_swear_exists above) already lives. GETPRC carries A7-A12 into a
 * created process, so the wrestler number captured at CREATE time is
 * captured here too rather than read again when the call fires.
 * ================================================================== */

/*
 * The source has as many SOUND_PID processes as it has free process slots.
 * Eight in flight is far past what the sequence files can start at once
 * (each is 5-15 ticks long and no animation calls two in a frame), and a
 * full list drops the call rather than overwriting a queued one.
 */
#define WM_ANN_PENDING_SLOTS 8

static struct {
    const wm_announce_table *table;
    wm_announcer_state *announcer;
    WmRng *rng;
    bool (*near_death)(void *user);
    void *user;
    /* GETPRC carries the crowd seam into the created process the same way
       it carries everything else the call needs. */
    void *crowd_user;
    void (*crowd_cheer)(void *user, int flags, int percent);
    void (*crowd_sound)(void *user, int sound, int ticks);
    bool (*crowd_busy)(void *user);
    uint16_t delay;
    uint16_t percent;
    int wrestler;              /* A5, or -1 when this caller never sets it */
} ann_pending[WM_ANN_PENDING_SLOTS];

static void announce_fire(size_t i) {
    wm_announce_ctx ctx;
    memset(&ctx, 0, sizeof(ctx));
    ctx.rng = ann_pending[i].rng;
    ctx.wrestler_num = ann_pending[i].wrestler;
    ctx.anyone_near_death = ann_pending[i].near_death;
    ctx.user = ann_pending[i].user;
    ctx.crowd_user = ann_pending[i].crowd_user;
    ctx.crowd_cheer = ann_pending[i].crowd_cheer;
    ctx.crowd_sound = ann_pending[i].crowd_sound;
    ctx.crowd_busy = ann_pending[i].crowd_busy &&
        ann_pending[i].crowd_busy(ann_pending[i].crowd_user);
    /* Every one of these callers uses ADD_IF_SILENT, not ADD_TO_QUEUE. */
    (void)wm_announce_from_table(ann_pending[i].announcer,
                                 ann_pending[i].table,
                                 ann_pending[i].percent, true, &ctx);
}

/*
 * LIFEBAR.ASM:3687 DO_COMBO_MESS, the most-called ANI_CODE routine in the
 * game at 193 sites. The logic is wm_arcade_do_combo_mess; this is the
 * bridge that hands it the services the env carries.
 */
static void do_combo_mess(wm_arcade_actor_t *actor, const wm_anim_env *env,
                          int32_t param) {
    wm_combo_mess_ctx ctx;
    (void)param;
    memset(&ctx, 0, sizeof(ctx));
    if (env) {
        ctx.sound_user = env->sound_user;
        ctx.sound = env->sound;
        ctx.announcer = env->announcer;
        ctx.award_user = env->award_user;
        ctx.round_award = env->round_award;
    }
    (void)wm_arcade_do_combo_mess(actor, &ctx);
}

/*
 * WRESTLE.ASM:6069 shake_all_ropes -- every bank at once,
 * `ROPE_BOUNCEUD` with the source's own selector of 2. Its NUM_OPPS guard
 * ("no shaking with two or more") is commented out in the source and is
 * left that way here.
 */
static void shake_all_ropes(wm_arcade_actor_t *actor, const wm_anim_env *env,
                            int32_t param) {
    static const int banks[4] = { WM_ROPE_FRONT, WM_ROPE_BACK,
                                  WM_ROPE_LEFT, WM_ROPE_RIGHT };
    size_t i;
    (void)param;
    if (!env || !env->rope_command) return;
    for (i = 0; i < 4; ++i)
        env->rope_command(env->rope_user, banks[i], WM_ROPE_BOUNCE_UD, 2,
                          actor ? actor->z_fixed : 0);
}

/*
 * WRESTLE.ASM:5978 get_leap -- may he lunge, or is he backing off?
 *
 * MODE_STATUS comes off first, and goes back on for "no": standing still
 * (both X and Z velocity zero), or holding the stick the way `mv_tbl` says
 * is AWAY for the direction he is facing. The table is four live rows in
 * sixteen -- NEW_FACING_DIR is only ever 5, 6, 9 or 10 (the source says
 * so in its own comment) -- and it reads a facing of 5 or 6 as "away is
 * right", 9 or 10 as "away is left".
 */
static void get_leap(wm_arcade_actor_t *actor, const wm_anim_env *env,
                     int32_t param) {
    int32_t away;
    (void)env;
    (void)param;
    if (!actor) return;
    actor->anim_mode &= (uint16_t)~WM_MODE_STATUS;

    if (actor->x_vel == 0 && actor->z_vel == 0) {   /* `jrz #novel` */
        actor->anim_mode |= (uint16_t)WM_MODE_STATUS;
        return;
    }
    /*
     * WRESTLE.ASM:6035 mv_tbl, indexed by NEW_FACING_DIR, holding a BIT
     * NUMBER for `btst a0,a1`. Facing up-left or down-left (5, 6), away
     * is right; facing up-right or down-right (9, 10), away is left.
     * Every other row is a literal 0, and `btst 0` is the UP bit -- not a
     * no-op. update_newfacing can only ever produce 5, 6, 9 or 10 (the
     * source says as much in its own comment), so those rows are dead,
     * but they are translated as written rather than as "nothing".
     */
    switch (actor->new_facing_dir) {
    case WM_MOVE_UP_LEFT:   case WM_MOVE_DOWN_LEFT:  away = WM_MOVE_RIGHT; break;
    case WM_MOVE_UP_RIGHT:  case WM_MOVE_DOWN_RIGHT: away = WM_MOVE_LEFT;  break;
    default:                                         away = WM_MOVE_UP;   break;
    }
    if (actor->move_dir & away)
        actor->anim_mode |= (uint16_t)WM_MODE_STATUS;
}

/*
 * WRESTLE2.ASM:3748 hit_nearest -- "set WHOIHIT and victim WHOPINNEDME",
 * and the victim's PINNED bit with them. CLOSEST_NUM is the fixed
 * opponent in this port (see wm/arcade/wm_arcade_closest.h for why), so
 * the process-table walk is the smart target.
 */
static void hit_nearest(wm_arcade_actor_t *actor, const wm_anim_env *env,
                        int32_t param) {
    wm_arcade_actor_t *victim;
    (void)param;
    if (!actor) return;
    victim = actor->smart_target ? actor->smart_target
                                 : (env ? env->opponent : NULL);
    if (!victim) return;
    actor->who_i_hit = victim;
    victim->who_pinned_me = actor;
    victim->status_flags |= (uint32_t)WM_STATUS_PINNED;
}

/*
 * WRESTLE2.ASM:3040 set_tbukl_confine -- climbing a turnbuckle, and
 * whether the ring is allowed to hold you in while you do it.
 *
 * The sweep asks one question of every opponent: is anybody on the other
 * team OUTSIDE the ring? If so this wrestler gets MODE_NOCONFINE, because
 * the attack he is about to launch has to be able to follow them out.
 * Otherwise NOCONFINE comes off -- and, since he may have drifted out
 * already, he is yanked back: INRING cleared, GROUND_Y put back on the
 * mat, Z clamped to RING_TOP, and X clamped to whichever rope line he is
 * on the wrong side of, through calc_line_x.
 *
 * Two details that are easy to lose. Yokozuna skips the sweep outright
 * (`cmpi W_YOKO / jreq #clear_noconfine`) and is always confined. And the
 * "everyone on the enemy side is dead" flag, taken from the CLOSEST
 * opponent's PLYRMODE, does not make the routine give up -- it makes it
 * STOP SKIPPING dead opponents, so a dead man lying outside the ropes
 * still grants NOCONFINE.
 *
 * INRING's polarity is the source's, not this port's: PLYR.EQU:103 says
 * 0 = in the ring, so `jrnz #set_noconfine` fires for a wrestler who is
 * OUT. The port stores the ordinary boolean, so the test flips.
 */
static void set_tbukl_confine(wm_arcade_actor_t *actor, const wm_anim_env *env,
                              int32_t param) {
    wm_arcade_actor_t *opp;
    bool other_team_dead;
    (void)param;
    if (!actor) return;

    if (actor->wrestler_num != WM_ROSTER_YOKO) {
        opp = actor->smart_target ? actor->smart_target
                                  : (env ? env->opponent : NULL);
        /* `a3 is the 'everyone is dead' flag`, from CLOSEST_NUM alone. */
        other_team_dead = opp && opp->player_mode == WM_PMODE_DEAD;
        /* The sweep skips inactive slots, self, and teammates; in a
           1-on-1 match that leaves exactly the opponent. */
        if (opp && opp->active && opp->player_side != actor->player_side &&
            (other_team_dead || opp->player_mode != WM_PMODE_DEAD) &&
            !opp->in_ring) {
            actor->anim_mode |= (uint16_t)WM_MODE_NOCONFINE;
            return;                                /* `#set_noconfine` */
        }
    }

    /* `#clear_noconfine`: "he might have drifted out already, so we gotta
       yank 'em back in." */
    if (!actor->in_ring) {
        actor->in_ring = 1;
        actor->ground_y = WM_MAT_Y;
        if (actor->z_int < WM_RING_TOP) {
            actor->z_int = WM_RING_TOP;
            actor->z_fixed = (int32_t)WM_RING_TOP << 16;
        }
        if (actor->x_int <= WM_RING_X_CENTER) {    /* `jrgt #rt` */
            int32_t x = wm_ring_calc_line_x(
                wm_ring_boundary_seed(WM_RING_BOUNDARY_LEFT_ROPE),
                actor->z_int);
            /* `jrz #xok` -- "bad news. leave it alone." -- and then
               `cmp a0,a2 / jrge #xok`, so he is pushed only when he is
               already left OF the left rope line. */
            if (x != 0 && actor->x_int < x) {
                actor->x_int = x;
                actor->x_fixed = x << 16;
            }
        } else {
            int32_t x = wm_ring_calc_line_x(
                wm_ring_boundary_seed(WM_RING_BOUNDARY_RIGHT_ROPE),
                actor->z_int);
            if (x != 0 && actor->x_int > x) {   /* `jrle #xok` */
                actor->x_int = x;
                actor->x_fixed = x << 16;
            }
        }
    }
    actor->anim_mode &= (uint16_t)~WM_MODE_NOCONFINE;
}

/*
 * DNKSEQ2.ASM:5202 win_announce, the whole of it:
 *
 *     move  a13,a10
 *     CREATE ANNC_PID,announce_rnd_winner
 *     CALLA KILL_PIN_HIM
 *
 * A pin animation calls it the moment the pin sticks. Everything it does
 * is in the process it starts, which is what actually ends the round --
 * so this is a seam onto the match, exactly like the crowd and the ropes.
 * `move a13,a10` is the source handing the process its creator through
 * GETPRC's register carry, which is how announce_rnd_winner knows whose
 * PLYR_SIDE to announce; the port's own set_winner finds him from the
 * roster instead, the same search the source runs a few lines later.
 */
static void win_announce(wm_arcade_actor_t *actor, const wm_anim_env *env,
                         int32_t param) {
    (void)actor;
    (void)param;
    if (!env || !env->win_announce) return;
    env->win_announce(env->round_user);
}

/*
 * DNKSEQ2.ASM:5221 grnd_hit, "FOR USE ONLY IN PINS!"
 *
 * The pinner hits the man he is pinning, and the source argues with
 * itself about whose pointer to use for it -- one comment says use
 * CLOSEST because you do not actually attack during a pin, and the
 * comment below it overrules that: "Un! DO use WHOIHIT, as this is set in
 * all the pin_anims before this function is called." So WHOIHIT it is,
 * and the commented-out CLOSEST_NUM walk is left where it was.
 *
 * Two halves. The victim is put into his own hitonground animation,
 * looked up in `#hit_t` by HIS wrestler number, through the same
 * change_anim1a seam ANI_SLAVEANIM uses. Then the two are aligned in Z --
 * pinner to victim+1.0, victim to victim-1.0, so the pinner draws in
 * front -- unless the PINNER is the Undertaker (`subk 2,a0 / jrz #z`),
 * who is left where he is.
 */
#define WM_GRND_HIT_Z_GAP 0x10000       /* the source's own [1,0] */

static void grnd_hit(wm_arcade_actor_t *actor, const wm_anim_env *env,
                     int32_t param) {
    wm_arcade_actor_t *victim;
    const char *label;
    int32_t z;
    (void)param;

    if (!actor) return;
    victim = actor->who_i_hit;
    if (!victim) return;                          /* `jrz` on a null WHOIHIT */

    label = wm_anim_code_roster_label("grnd_hit", victim->wrestler_num);
    if (label && env && env->change_opp_anim) {
        victim->puppet_frame = 0;      /* he drives himself again now */
        env->change_opp_anim(victim, label, env->slave_user);
    }

    /* "align on target's z, unless we're taker" */
    if (actor->wrestler_num == WM_ROSTER_TAKER) return;

    z = victim->z_fixed;
    actor->z_fixed = z + WM_GRND_HIT_Z_GAP;
    actor->z_int = actor->z_fixed >> 16;
    victim->z_fixed = z - WM_GRND_HIT_Z_GAP;
    victim->z_int = victim->z_fixed >> 16;
}

