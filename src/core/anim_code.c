static void zero_butn(wm_arcade_actor_t *actor, const wm_anim_env *env,
                      int32_t param) {
    (void)env;
    if (!actor) return;
    if (param) actor->powerp_dtime = 0;
    else actor->punch_dtime = 0;
}

