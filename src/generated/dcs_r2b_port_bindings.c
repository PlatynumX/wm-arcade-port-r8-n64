const wm_dcs_port_binding *wm_dcs_port_binding_at(size_t index) {
    if (index >= wm_dcs_port_binding_count()) return 0;
    return &wm_dcs_r2b_bindings[index];
}

const wm_dcs_port_binding *wm_dcs_find_first_binding_for_command(uint16_t command) {
    for (size_t i = 0; i < wm_dcs_port_binding_count(); ++i) {
        if (wm_dcs_r2b_bindings[i].command == command)
            return &wm_dcs_r2b_bindings[i];
    }
    return 0;
}

bool wm_dcs_command_has_decoded_binding(uint16_t command) {
    return wm_dcs_find_first_binding_for_command(command) != 0;
}

